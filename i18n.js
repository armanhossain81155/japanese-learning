let lang = (() => {
  try { return localStorage.getItem('nd-lang') || 'en'; } catch (e) { return 'en'; }
})();

// Translate a UI key
function t(key, ...args) {
  const s = I18N[lang][key] ?? I18N.en[key] ?? key;
  return typeof s === 'function' ? s(...args) : s;
}

// Pick the current language from a T(en, bn) data value; plain strings pass through
function L(v) {
  return v && typeof v === 'object' && 'en' in v ? (v[lang] ?? v.en) : v;
}

// Translate static markup in index.html (data-i18n, data-i18n-arg, data-i18n-attr)
function applyStaticI18n() {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n, el.dataset.i18nArg);
  });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    const [attr, key] = el.dataset.i18nAttr.split(':');
    el.setAttribute(attr, t(key));
    if (attr === 'aria-label') el.title = t(key);
  });
}
